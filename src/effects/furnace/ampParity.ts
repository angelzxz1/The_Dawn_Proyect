// The Furnace amp's parity fixture for its Rust port
// (crates/dawn-engine/src/effects/amp.rs): the cases, rendered with the
// worklet's own kernel (ampKernel.ts, its settings from ampModel.ts) the way
// the worklet runs it (ampSim.ts) - a render quantum at a time, on the mono
// mix of the input (the node's one input channel takes stereo down-mixed,
// 0.5 * (L + R)) - as a generated Rust file and the rendered samples.
// ampParity.test.ts checks the stored fixture still matches; the Rust
// side's tests/amp_parity.rs compares the port against it. See
// src/test/kernelParity.ts.

import { AMP_SOURCE, type AmpSettings } from "./ampKernel";
import { ampSettingsFromParams } from "./ampModel";
import { FixtureData, PARITY_BLOCK, PARITY_FRAMES, PARITY_SAMPLE_RATE, PARITY_STRIDE, fnv1a, paritySignal, rustF64, rustHex, type ParitySignal } from "../../test/kernelParity";

interface Kernel {
  set(s: AmpSettings): void;
  process(input: Float32Array | null, output: Float32Array, n: number): void;
}

const Amp = new Function(`${AMP_SOURCE}; return AmpKernel;`)() as new (sr: number) => Kernel;

export interface AmpParityCase {
  name: string;
  params: Record<string, number>;
  /** New parameters (over the case's) from this frame on - a block start. */
  change?: { at: number; params: Record<string, number> };
}

export const AMP_PARITY_CASES: AmpParityCase[] = [
  { name: "modern-defaults", params: {} },
  { name: "vintage-tube", params: { mode: 1, rectifier: 0, gain: 5 } },
  { name: "raw", params: { mode: 0, gain: 8, treble: 7 } },
  { name: "clean-and-bright", params: { gain: 1, master: 3, output: 6 } },
  { name: "tone-extremes", params: { bass: 0, mid: 10, treble: 10, presence: 0, master: 10 } },
  { name: "scooped", params: { bass: 10, mid: 0, treble: 2, presence: 10, gain: 10 } },
  { name: "knobs-moved", params: { gain: 4 }, change: { at: 60 * PARITY_BLOCK, params: { gain: 9, bass: 3, mid: 8, master: 7, mode: 1 } } },
];

const changeParams = (c: AmpParityCase) => (c.change ? { ...c.params, ...c.change.params } : null);

function renderCase(c: AmpParityCase, sig: ParitySignal) {
  const k = new Amp(PARITY_SAMPLE_RATE);
  k.set(ampSettingsFromParams(c.params));
  const changed = changeParams(c);
  // The node's one input channel: the stereo input down-mixed.
  const mono = new Float32Array(PARITY_FRAMES);
  for (let i = 0; i < PARITY_FRAMES; i++) mono[i] = 0.5 * (sig.inL[i] + sig.inR[i]);
  const out = new Float32Array(PARITY_FRAMES);
  for (let start = 0; start < PARITY_FRAMES; start += PARITY_BLOCK) {
    if (c.change && changed && start === c.change.at) k.set(ampSettingsFromParams(changed));
    const n = Math.min(PARITY_BLOCK, PARITY_FRAMES - start);
    k.process(mono.subarray(start, start + n), out.subarray(start, start + n), n);
  }
  return out;
}

const rustParams = (p: Record<string, number>) => `&[${Object.entries(p).map(([k, v]) => `("${k}", ${rustF64(v)})`).join(", ")}]`;

function rustCase(c: AmpParityCase): string {
  const changed = changeParams(c);
  return [
    "    Case {",
    `        name: "${c.name}",`,
    `        params: ${rustParams(c.params)},`,
    `        change: ${c.change && changed ? `Some((${c.change.at}, ${rustParams(changed)}))` : "None"},`,
    "    },",
  ].join("\n");
}

/** The fixture as it should be now: the Rust file's text, and the data
 * (per case: the kept samples of the amp's one output). */
export function renderAmpParity(): { rust: string; data: FixtureData } {
  const sig = paritySignal();
  const data = new FixtureData();
  for (const c of AMP_PARITY_CASES) data.f32(renderCase(c, sig).filter((_, i) => i % PARITY_STRIDE === 0));
  const rust = [
    "// @generated by src/effects/furnace/ampParity.test.ts from the JavaScript",
    "// kernel (ampKernel.ts, ampModel.ts). Don't edit it: to remake it, run",
    "// UPDATE_ENGINE_FIXTURES=1 npx vitest run --project unit ampParity",
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${PARITY_FRAMES};`,
    `const BLOCK: usize = ${PARITY_BLOCK};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    `const SIGNAL_HASH: u32 = ${rustHex(fnv1a([sig.inL, sig.inR, sig.keyL, sig.keyR]))};`,
    "",
    "const CASES: &[Case] = &[",
    ...AMP_PARITY_CASES.map(rustCase),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}
