// The Utility's parity fixture for its Rust port
// (crates/dawn-engine/src/effects/utility.rs): the cases, rendered by the
// worklet's own kernel (utilityModel.ts) the way the worklet runs it, as a
// generated Rust file and the rendered samples and meters.
// utilityParity.test.ts checks the stored fixture still matches; the Rust
// side's tests/utility_parity.rs compares the port against it. See
// src/test/kernelParity.ts.

import { UTILITY_SOURCE, utilitySettingsFromParams, type UtilitySettings } from "./utilityModel";
import { FixtureData, PARITY_BLOCK, PARITY_FRAMES, PARITY_SAMPLE_RATE, PARITY_STRIDE, fnv1a, paritySignal, rustF64, rustHex, type ParitySignal } from "../../test/kernelParity";

interface Meters {
  peakL: number;
  peakR: number;
  correlation: number;
}

interface Kernel {
  set(s: UtilitySettings): void;
  process(inL: Float32Array | null, inR: Float32Array | null, outL: Float32Array, outR: Float32Array | null, n: number): void;
  takeMeters(): Meters;
}

const Utility = new Function(`${UTILITY_SOURCE}; return UtilityKernel;`)() as new (sr: number) => Kernel;

/** How often (frames) the worklet reads the meters (utility.ts). */
export const UTILITY_PARITY_METER_INTERVAL = 2048;

export interface UtilityParityCase {
  name: string;
  params: Record<string, number>;
  input: "mono" | "stereo";
  /** New parameters from this frame on - a block start. */
  change?: { at: number; params: Record<string, number> };
}

export const UTILITY_PARITY_CASES: UtilityParityCase[] = [
  { name: "defaults", params: {}, input: "stereo" },
  { name: "wide-bass-mono-balanced", params: { width: 2.5, bassMono: 1, bassFreq: 150, balance: 0.3, gain: -3 }, input: "stereo" },
  { name: "mono-inverted-swapped", params: { mono: 1, invertL: 1, channel: 3, gain: 4 }, input: "stereo" },
  { name: "dc-left-quiet", params: { dcFilter: 1, channel: 1, gain: -6, balance: -0.6, width: 0 }, input: "stereo" },
  { name: "mono-input-right", params: { channel: 2, invertR: 1, width: 3, bassMono: 1, bassFreq: 400 }, input: "mono" },
  // Moving gain, width and balance glides; muting fades out.
  { name: "gliding", params: { gain: 0, width: 1 }, input: "stereo", change: { at: 60 * PARITY_BLOCK, params: { gain: 6, width: 0.2, balance: 0.8 } } },
  { name: "muted", params: { gain: 2 }, input: "stereo", change: { at: 40 * PARITY_BLOCK, params: { gain: 2, mute: 1 } } },
  { name: "at-the-floor", params: { gain: -60, bassMono: 1 }, input: "stereo", change: { at: 20 * PARITY_BLOCK, params: { gain: -59.5, channel: 1.6 } } },
];

function renderCase(c: UtilityParityCase, sig: ParitySignal) {
  const k = new Utility(PARITY_SAMPLE_RATE);
  k.set(utilitySettingsFromParams(c.params));
  const outL = new Float32Array(PARITY_FRAMES);
  const outR = new Float32Array(PARITY_FRAMES);
  const meters: Meters[] = [];
  let count = 0;
  for (let start = 0; start < PARITY_FRAMES; start += PARITY_BLOCK) {
    if (c.change && start === c.change.at) k.set(utilitySettingsFromParams(c.change.params));
    const n = Math.min(PARITY_BLOCK, PARITY_FRAMES - start);
    const part = (a: Float32Array) => a.subarray(start, start + n);
    k.process(part(sig.inL), c.input === "stereo" ? part(sig.inR) : null, part(outL), part(outR), n);
    count += n;
    if (count >= UTILITY_PARITY_METER_INTERVAL) {
      count = 0;
      meters.push(k.takeMeters());
    }
  }
  return { outL, outR, meters };
}

const rustParams = (p: Record<string, number>) => `&[${Object.entries(p).map(([k, v]) => `("${k}", ${rustF64(v)})`).join(", ")}]`;

function rustCase(c: UtilityParityCase): string {
  return [
    "    Case {",
    `        name: "${c.name}",`,
    `        params: ${rustParams(c.params)},`,
    `        mono: ${c.input === "mono"},`,
    `        change: ${c.change ? `Some((${c.change.at}, ${rustParams(c.change.params)}))` : "None"},`,
    "    },",
  ].join("\n");
}

/** The fixture as it should be now: the Rust file's text, and the data
 * (per case: the kept left and right samples, then each meter reading's
 * peaks and correlation). */
export function renderUtilityParity(): { rust: string; data: FixtureData } {
  const sig = paritySignal();
  const data = new FixtureData();
  for (const c of UTILITY_PARITY_CASES) {
    const { outL, outR, meters } = renderCase(c, sig);
    for (const out of [outL, outR]) data.f32(out.filter((_, i) => i % PARITY_STRIDE === 0));
    data.f64(meters.flatMap((m) => [m.peakL, m.peakR, m.correlation]));
  }
  const rust = [
    "// @generated by src/effects/utility/utilityParity.test.ts from the",
    "// JavaScript kernel (utilityModel.ts). Don't edit it: to remake it,",
    "// run UPDATE_ENGINE_FIXTURES=1 npx vitest run --project unit utilityParity",
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${PARITY_FRAMES};`,
    `const BLOCK: usize = ${PARITY_BLOCK};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    `const METER_INTERVAL: usize = ${UTILITY_PARITY_METER_INTERVAL};`,
    `const SIGNAL_HASH: u32 = ${rustHex(fnv1a([sig.inL, sig.inR, sig.keyL, sig.keyR]))};`,
    "",
    "const CASES: &[Case] = &[",
    ...UTILITY_PARITY_CASES.map(rustCase),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}
