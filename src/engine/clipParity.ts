// Audio clips' parity fixture for the native engine
// (crates/dawn-engine/src/mix/clip.rs): overlapping clips on a timeline -
// mono and stereo files, part of a file, loops, fades, gain, one running
// past its file's end - mixed by mixClip (clipAudio.ts), as a generated
// Rust file and the mixed samples. clipParity.test.ts checks the stored
// fixture still matches; the Rust side's tests/clip_parity.rs plays the
// same clips in blocks and compares.

import { mixClip } from "./clipAudio";
import type { AudioClipInstance } from "../project/types";
import { FixtureData, PARITY_FRAMES, PARITY_SAMPLE_RATE, PARITY_STRIDE, fnv1a, paritySignal, rustF64, rustHex } from "../test/kernelParity";

type Timing = Pick<AudioClipInstance, "offset" | "length" | "sourceOffset" | "loopLength" | "gainDb" | "fadeIn" | "fadeOut">;

export interface ClipParityCase {
  /** The parity signal's left channel alone, or both. */
  file: "mono" | "stereo";
  timing: Timing;
}

const plain = { sourceOffset: 0, loopLength: null, gainDb: 0, fadeIn: 0, fadeOut: 0 };

export const CLIP_PARITY_CASES: ClipParityCase[] = [
  { file: "mono", timing: { ...plain, offset: 0.01, length: 0.2, sourceOffset: 0.05, gainDb: -3, fadeIn: 0.02, fadeOut: 0.05 } },
  { file: "stereo", timing: { ...plain, offset: 0.1, length: 0.25, loopLength: 0.07, gainDb: 2, fadeIn: 0.005, fadeOut: 0.1 } },
  // Runs 0.15 s past its file's end.
  { file: "stereo", timing: { ...plain, offset: 0.3, length: 0.2, sourceOffset: 0.35 } },
  // All fade.
  { file: "mono", timing: { ...plain, offset: 0.37, length: 0.03, fadeIn: 0.03, fadeOut: 0.03 } },
  // Between frames, looped from part of the file.
  { file: "mono", timing: { ...plain, offset: 0.123456, length: 0.1, sourceOffset: 0.2, loopLength: 0.011, gainDb: -12, fadeOut: 0.004 } },
];

/** The timeline mixed: what the clips play over PARITY_FRAMES from 0. */
function renderClips(): [Float32Array, Float32Array] {
  const sig = paritySignal();
  const out: [Float32Array, Float32Array] = [new Float32Array(PARITY_FRAMES), new Float32Array(PARITY_FRAMES)];
  for (const c of CLIP_PARITY_CASES) {
    const clip = { ...c.timing, id: "clip", kind: "audio", url: "", name: "" } as unknown as AudioClipInstance;
    mixClip(out, 0, PARITY_SAMPLE_RATE, { clip, channels: c.file === "mono" ? [sig.inL] : [sig.inL, sig.inR] });
  }
  return out;
}

function rustCase(c: ClipParityCase): string {
  const t = c.timing;
  return [
    "    Case {",
    `        stereo: ${c.file === "stereo"},`,
    "        timing: ClipTiming {",
    `            offset: ${rustF64(t.offset)},`,
    `            length: ${rustF64(t.length)},`,
    `            source_offset: ${rustF64(t.sourceOffset)},`,
    `            loop_length: ${t.loopLength ? `Some(${rustF64(t.loopLength)})` : "None"},`,
    `            gain_db: ${rustF64(t.gainDb)},`,
    `            fade_in: ${rustF64(t.fadeIn)},`,
    `            fade_out: ${rustF64(t.fadeOut)},`,
    "        },",
    "    },",
  ].join("\n");
}

/** The fixture as it should be now: the Rust file's text, and the data
 * (the kept left and right samples). */
export function renderClipParity(): { rust: string; data: FixtureData } {
  const sig = paritySignal();
  const data = new FixtureData();
  for (const out of renderClips()) data.f32(out.filter((_, i) => i % PARITY_STRIDE === 0));
  const rust = [
    "// @generated by src/engine/clipParity.test.ts from mixClip",
    "// (clipAudio.ts). Don't edit it: to remake it, run",
    "// UPDATE_ENGINE_FIXTURES=1 npx vitest run --project unit clipParity",
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${PARITY_FRAMES};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    `const SIGNAL_HASH: u32 = ${rustHex(fnv1a([sig.inL, sig.inR, sig.keyL, sig.keyR]))};`,
    "",
    "const CASES: &[Case] = &[",
    ...CLIP_PARITY_CASES.map(rustCase),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}
