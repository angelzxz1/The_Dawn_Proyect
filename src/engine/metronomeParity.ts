// The metronome's parity fixture for its Rust port
// (crates/dawn-engine/src/mix/metronome.rs): a session of commands (a
// count-in, a tempo change, a loop, a jump, the click turned off and on, a
// stop and a new start), rendered by the kernel the way its worklet runs
// it, as a generated Rust file and the rendered samples.
// metronomeParity.test.ts checks the stored fixture still matches; the Rust
// side's tests/metronome_parity.rs plays the same session and compares.

import { METRONOME_KERNEL_SOURCE } from "./metronomeKernel";
import { FixtureData, PARITY_BLOCK, PARITY_SAMPLE_RATE, PARITY_STRIDE, rustF64 } from "../test/kernelParity";

interface Kernel {
  command(m: Record<string, unknown>): void;
  render(out: Float32Array, time: number): void;
}

const { MetronomeKernel } = new Function(`${METRONOME_KERNEL_SOURCE}; return { MetronomeKernel };`)() as {
  MetronomeKernel: new (sampleRate: number) => Kernel;
};

type Segment = { beat: number; seconds: number; bpm: number };
type Command =
  | { type: "start"; time: number; pos: number; countInBeats: number }
  | { type: "stop" }
  | { type: "resync"; time: number; pos: number }
  | { type: "enabled"; enabled: boolean }
  | { type: "tempo"; segments: Segment[] }
  | { type: "meter"; beatsPerBar: number }
  | { type: "loop"; loop: { start: number; end: number } | null };

/** 6 s. */
export const METRONOME_PARITY_FRAMES = 6 * PARITY_SAMPLE_RATE;

/** The block a command at engine time `t` (s) arrives with. */
const at = (t: number) => Math.round((t * PARITY_SAMPLE_RATE) / PARITY_BLOCK) * PARITY_BLOCK;

/** The session: commands, each at a block start. */
export const METRONOME_SESSION: { at: number; command: Command }[] = [
  // 120 BPM, then 90 from beat 8 (at 4 s); three beats a bar; a loop over
  // 4.5-5.25 s; two beats of count-in, then the transport from 3 s at 1.2 s.
  {
    at: 0,
    command: {
      type: "tempo",
      segments: [
        { beat: 0, seconds: 0, bpm: 120 },
        { beat: 8, seconds: 4, bpm: 90 },
      ],
    },
  },
  { at: 0, command: { type: "meter", beatsPerBar: 3 } },
  { at: 0, command: { type: "enabled", enabled: true } },
  { at: 0, command: { type: "loop", loop: { start: 4.5, end: 5.25 } } },
  { at: 0, command: { type: "start", time: 1.2, pos: 3, countInBeats: 2 } },
  { at: at(2), command: { type: "enabled", enabled: false } },
  { at: at(2.6), command: { type: "enabled", enabled: true } },
  // A jump back to 1 s.
  { at: at(3), command: { type: "resync", time: 3, pos: 1 } },
  // No loop, and one tempo (100 BPM) from 2 s on the transport.
  { at: at(4), command: { type: "loop", loop: null } },
  { at: at(4), command: { type: "tempo", segments: [{ beat: 0, seconds: 0, bpm: 100 }] } },
  { at: at(4), command: { type: "resync", time: 4, pos: 2 } },
  { at: at(4.5), command: { type: "meter", beatsPerBar: 4 } },
  { at: at(5), command: { type: "stop" } },
  // Playing again from half a second in, straight away.
  { at: at(5.2), command: { type: "start", time: 5.3, pos: 0.5, countInBeats: 0 } },
];

function renderSession(): Float32Array {
  const kernel = new MetronomeKernel(PARITY_SAMPLE_RATE);
  const out = new Float32Array(METRONOME_PARITY_FRAMES);
  let next = 0;
  for (let start = 0; start < METRONOME_PARITY_FRAMES; start += PARITY_BLOCK) {
    while (next < METRONOME_SESSION.length && METRONOME_SESSION[next].at === start) kernel.command(METRONOME_SESSION[next++].command);
    kernel.render(out.subarray(start, start + PARITY_BLOCK), start / PARITY_SAMPLE_RATE);
  }
  return out;
}

function rustSegments(segments: Segment[]): string {
  return `&[${segments.map((s) => `TempoSegment { beat: ${rustF64(s.beat)}, seconds: ${rustF64(s.seconds)}, bpm: ${rustF64(s.bpm)} }`).join(", ")}]`;
}

function rustCommand(c: Command): string {
  switch (c.type) {
    case "start":
      return `Command::Start { time: ${rustF64(c.time)}, pos: ${rustF64(c.pos)}, count_in_beats: ${rustF64(c.countInBeats)} }`;
    case "stop":
      return "Command::Stop";
    case "resync":
      return `Command::Resync { time: ${rustF64(c.time)}, pos: ${rustF64(c.pos)} }`;
    case "enabled":
      return `Command::Enabled(${c.enabled})`;
    case "tempo":
      return `Command::Tempo(${rustSegments(c.segments)})`;
    case "meter":
      return `Command::Meter(${rustF64(c.beatsPerBar)})`;
    case "loop":
      return `Command::Loop(${c.loop ? `Some(Loop { start: ${rustF64(c.loop.start)}, end: ${rustF64(c.loop.end)} })` : "None"})`;
  }
}

/** The fixture as it should be now: the Rust file's text, and the data
 * (the kept samples). */
export function renderMetronomeParity(): { rust: string; data: FixtureData } {
  const out = renderSession();
  const data = new FixtureData();
  data.f32(out.filter((_, i) => i % PARITY_STRIDE === 0));
  const rust = [
    "// @generated by src/engine/metronomeParity.test.ts from the JavaScript",
    "// kernel (metronomeKernel.ts). Don't edit it: to remake it, run",
    "// UPDATE_ENGINE_FIXTURES=1 npx vitest run --project unit metronomeParity",
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${METRONOME_PARITY_FRAMES};`,
    `const BLOCK: usize = ${PARITY_BLOCK};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    "",
    "const SESSION: &[(usize, Command)] = &[",
    ...METRONOME_SESSION.map((s) => `    (${s.at}, ${rustCommand(s.command)}),`),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}
