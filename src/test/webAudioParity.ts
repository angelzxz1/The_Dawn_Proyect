// The parity fixtures of the effects built from the browser's own audio
// nodes (BiquadFilter, Gain and the rest, through Tone.js) rather than a
// kernel of ours: those nodes only run in a browser, so the cases are
// rendered in Chromium (Vitest's browser mode, the "web-audio" project in
// vitest.config.ts) through an OfflineAudioContext, by the same nodes the
// studio builds. The fixture's files are as kernelParity.ts describes. The
// Rust ports follow Chromium's code, but its maths library and the order
// it sums a node's inputs in can round differently in the last bit, so
// both checks here and the Rust side's are looser than a kernel's.

import * as Tone from "tone";
import { commands } from "@vitest/browser/context";
import { describe, expect, inject, it } from "vitest";
import type { EffectAudio, EffectDefinition } from "../effects/types";
import { FixtureData, PARITY_FRAMES, PARITY_SAMPLE_RATE, PARITY_STRIDE, fnv1a, paritySignal, rustF64, rustHex, type ParitySignal } from "./kernelParity";

declare module "vitest" {
  export interface ProvidedContext {
    /** UPDATE_ENGINE_FIXTURES=1: rewrite the fixtures instead of checking them. */
    updateEngineFixtures: boolean;
  }
}

/** One setting of an effect, and maybe a change to another. */
export interface WebAudioCase {
  name: string;
  /** Its parameters; the rest are at their defaults. */
  params: Record<string, number>;
  /** All the parameters from this frame on (a block start); those left
   * out go back to their defaults. */
  change?: { at: number; params: Record<string, number> };
}

const withDefaults = (effect: EffectDefinition, params: Record<string, number>) =>
  Object.fromEntries(effect.params.map((p) => [p.key, params[p.key] ?? p.default]));

/** One case through the effect's node, as the studio builds it and changes
 * its parameters (one set() a parameter). */
async function renderCase(effect: EffectDefinition, audio: EffectAudio, c: WebAudioCase, sig: ParitySignal) {
  const raw = new OfflineAudioContext(2, PARITY_FRAMES, PARITY_SAMPLE_RATE);
  const context = new Tone.Context({ context: raw as unknown as Tone.BaseContext["rawContext"], lookAhead: 0 });
  const previous = Tone.getContext();
  Tone.setContext(context);
  try {
    const params = withDefaults(effect, c.params);
    const node = audio.create(params);
    if (c.change) {
      const next = withDefaults(effect, c.change.params);
      // The new values are set at the suspension's time, so they start at
      // that frame.
      raw.suspend(c.change.at / PARITY_SAMPLE_RATE).then(() => {
        for (const p of effect.params) if (next[p.key] !== params[p.key]) audio.set(node, p.key, next[p.key]);
        return raw.resume();
      });
    }
    const input = raw.createBuffer(2, PARITY_FRAMES, PARITY_SAMPLE_RATE);
    input.copyToChannel(sig.inL as Float32Array<ArrayBuffer>, 0);
    input.copyToChannel(sig.inR as Float32Array<ArrayBuffer>, 1);
    const source = raw.createBufferSource();
    source.buffer = input;
    Tone.connect(source, node);
    node.connect(raw.destination);
    source.start(0);
    const out = await raw.startRendering();
    node.dispose();
    return { outL: out.getChannelData(0), outR: out.getChannelData(1) };
  } finally {
    Tone.setContext(previous);
  }
}

const rustParams = (p: Record<string, number>) => `&[${Object.entries(p).map(([k, v]) => `("${k}", ${rustF64(v)})`).join(", ")}]`;

function rustCase(c: WebAudioCase): string {
  return [
    "    Case {",
    `        name: "${c.name}",`,
    `        params: ${rustParams(c.params)},`,
    `        change: ${c.change ? `Some((${c.change.at}, ${rustParams(c.change.params)}))` : "None"},`,
    "    },",
  ].join("\n");
}

/** The fixture as Chromium renders it now: the Rust file's text, and the
 * data (per case, the kept left and right samples). `source` names the
 * effect's node file and `testName` its parity test, for the header. */
export async function renderWebAudioParity(
  effect: EffectDefinition,
  audio: EffectAudio,
  cases: WebAudioCase[],
  source: string,
  testName: string
): Promise<{ rust: string; data: FixtureData }> {
  const sig = paritySignal();
  const data = new FixtureData();
  for (const c of cases) {
    const { outL, outR } = await renderCase(effect, audio, c, sig);
    for (const out of [outL, outR]) data.f32(out.filter((_, i) => i % PARITY_STRIDE === 0));
  }
  const rust = [
    `// @generated by ${testName}.webaudio.test.ts, from what Chromium renders`,
    `// through the studio's nodes (${source}). Don't edit it: to remake it, run`,
    `// UPDATE_ENGINE_FIXTURES=1 npx vitest run --project web-audio ${testName}`,
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${PARITY_FRAMES};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    `const SIGNAL_HASH: u32 = ${rustHex(fnv1a([sig.inL, sig.inR, sig.keyL, sig.keyR]))};`,
    "",
    "const CASES: &[Case] = &[",
    ...cases.map(rustCase),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}

// The fixtures (the browser commands read and write from the project root).
const FIXTURE_DIR = "crates/dawn-engine/tests/fixtures";

function toBase64(bytes: Uint8Array): string {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(s);
}

const fromBase64 = (s: string) => Uint8Array.from(atob(s), (ch) => ch.charCodeAt(0));

/** The check on a fixture rendered in Chromium (as describeEngineFixture,
 * engineFixtures.ts, for the kernels): the stored one must be what renders
 * now, to within a float32 rounding or two. */
export function describeWebAudioFixture(what: string, name: string, testName: string, render: () => Promise<{ rust: string; data: FixtureData }>): void {
  const rustFile = `${FIXTURE_DIR}/${name}.rs`;
  const dataFile = `${FIXTURE_DIR}/${name}.bin`;
  const outOfDate =
    `${what} no longer renders the Rust port's fixture: remake it ` +
    `(UPDATE_ENGINE_FIXTURES=1 npx vitest run --project web-audio ${testName}) and port the change.`;
  let rendered: ReturnType<typeof render> | undefined;
  const now = () => (rendered ??= render());

  describe(`the Rust parity fixture "${name}"`, () => {
    if (inject("updateEngineFixtures")) {
      it("is rewritten", async () => {
        const { rust, data } = await now();
        await commands.writeFile(rustFile, rust);
        await commands.writeFile(dataFile, toBase64(data.bytes()), "base64");
      });
      return;
    }

    it("has the cases and settings rendered now", async () => {
      const stored = await commands.readFile(rustFile);
      expect(stored.replace(/\r\n/g, "\n"), outOfDate).toBe((await now()).rust);
    });

    it("has what's rendered now", async () => {
      const stored = fromBase64(await commands.readFile(dataFile, "base64"));
      expect((await now()).data.maxDifference(stored), outOfDate).toBeLessThanOrEqual(1e-6);
    });
  });
}
